// Deterministic SQL assembly only. Never connects to or changes a database.
import {readFile,writeFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
const base=new URL('../supabase/proposals/test-feature-parity/',import.meta.url);
const read=name=>readFile(new URL(name,base),'utf8');
const inner=sql=>sql.replace(/^begin;\s*$/mi,'').replace(/^(?:commit|rollback);\s*$/mi,'');
export async function buildRehearsal(installed=false){
 const components=installed?['02-rollback-checks.sql']:['00a-prepared-import-prerequisites.sql','01-prepared-apply.sql','02-rollback-checks.sql'];
 const body=(await Promise.all(components.map(read))).map(inner).join('\n');
 if(body.includes('$parity_package$'))throw Error('Package delimiter collision');
 return `-- GENERATED by tools/prepare-test-parity-rehearsal.mjs. PREPARED, NOT APPROVED.
-- ${installed?'Installed-state Test verification; existing repairs remain installed.':'One Test-only rollback rehearsal: nullable dates, duplicate safeguard, two RPCs,'}
-- four synthetic SQL Auth identities, two legal clients and temporary access grants.
-- No Auth API/email/provider requests. Run WHOLE query; never a selected fragment.
begin;
set local lock_timeout='3s';
set local statement_timeout='90s';
-- BEGIN HOSTED IDENTITY GUARD
do $$ begin if current_database()<>'postgres' or current_user<>'postgres' or (select system_identifier::text from pg_control_system())<>'7692130048193495360' then raise exception 'Expected reviewed BCM Test database and executor'; end if; end $$;
-- END HOSTED IDENTITY GUARD
${await read('03-preservation-snapshot.sql')}
create temporary table parity_hosted_summary(assertions bigint,all_passed boolean,existing_application_data_preserved boolean,schema_permissions_preserved boolean,auth_user_ids_preserved boolean);
do $rehearsal$
declare before_state jsonb; after_state jsonb; assertion_total bigint; assertions_passed boolean; rolled_back boolean:=false;
begin
 before_state:=pg_temp.parity_snapshot();
 begin
  execute $parity_package$${body}$parity_package$;
  select count(*),bool_and(passed) into assertion_total,assertions_passed from parity_results;
  if assertion_total<>18 or assertions_passed is distinct from true then raise exception 'Incomplete parity assertions'; end if;
  -- This exception intentionally rolls back the ENTIRE inner subtransaction.
  raise sqlstate 'P1980' using message='Successful rehearsal; undo all package changes';
 exception when sqlstate 'P1980' then rolled_back:=true;
 end;
 if not rolled_back then raise exception 'Inner rollback not verified'; end if;
 after_state:=pg_temp.parity_snapshot();
 if before_state is distinct from after_state then raise exception 'Existing data/schema/permissions or Auth user IDs changed; stop'; end if;
 insert into parity_hosted_summary values(assertion_total,assertions_passed,true,true,true);
end $rehearsal$;
select * from parity_hosted_summary;
rollback;
`;
}
export async function buildInstallation(){
 const body=(await Promise.all(['00a-prepared-import-prerequisites.sql','01-prepared-apply.sql'].map(read))).map(inner).join('\n');
 return `-- GENERATED by tools/prepare-test-parity-rehearsal.mjs. PREPARED ONLY.
-- Persistent BCM Test installation; separate approval required. Run WHOLE query.
-- Only three nullable date fields, one partial unique index, two guarded RPCs/grants.
-- No fixture identities, client records, engagement grants, worker deployment or email.
begin;
${body}
notify pgrst,'reload schema';
commit;
`;
}
if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href){
 const sql=await buildRehearsal();await writeFile(new URL('03-prepared-hosted-rehearsal.sql',base),sql);
 const installation=await buildInstallation();await writeFile(new URL('04-prepared-hosted-install.sql',base),installation);
 const verification=await buildRehearsal(true);await writeFile(new URL('05-prepared-installed-verification.sql',base),verification);
 console.log(JSON.stringify({status:'prepared-not-executed',rehearsal_bytes:Buffer.byteLength(sql),installation_bytes:Buffer.byteLength(installation),verification_bytes:Buffer.byteLength(verification)}));
}
